"""Close-vs-early drift: how far DraftKings' and Pinnacle's fair chances move between earlier
snapshots and the close (job C).

    python -m upsets.dk_close [--out reports/upsets_dk_close.md]

Reads only cached Odds API snapshots and Sackmann results (no paid calls, no Kalshi data). The
close = an event's last snapshot >= 5 min before its listed start with both books quoted. Every
earlier snapshot with both books is compared with it, by hours before the start. Fair chance =
proportional de-vig of each book's two prices. Aggregates only.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from . import dk_history as dh
from . import sackmann

LEAD_MIN = 5.0
BUCKETS_H = (0.0, 1.0, 3.0, 6.0, 12.0, 24.0, np.inf)


def pairs(j: pd.DataFrame, t: pd.DataFrame, snaps: pd.DataFrame, sack: pd.DataFrame) -> pd.DataFrame:
    """One row per (event, earlier snapshot): fair p(home) at DK and Pinnacle then and at the close,
    hours before the start, and (Sackmann events) whether home won."""
    ev = j[dh.needed(j, t)][["key", "event_id", "commence", "sack_row", "id_home"]].drop_duplicates("event_id")
    s = snaps[snaps["book"].isin(["draftkings", "pinnacle"])].merge(ev[["event_id", "commence"]], on="event_id")
    s = s[s["snapshot_ts"] <= s["commence"] - pd.Timedelta(minutes=LEAD_MIN)]
    s = s.sort_values("snapshot_ts").drop_duplicates(["event_id", "snapshot_ts", "book"], keep="last")
    s["p"] = (1 / s["odds_1"]) / (1 / s["odds_1"] + 1 / s["odds_2"])
    w = s.pivot(index=["event_id", "snapshot_ts"], columns="book", values="p").dropna().reset_index()
    w = w.rename(columns={"draftkings": "dk", "pinnacle": "pin"}).sort_values(["event_id", "snapshot_ts"])
    close = w.drop_duplicates("event_id", keep="last").set_index("event_id")
    early = w[w.duplicated("event_id", keep="last")].copy()
    early = early.join(close[["snapshot_ts", "dk", "pin"]], on="event_id", rsuffix="_close")
    early = early.merge(ev, on="event_id")
    early["hours"] = (early["commence"] - early["snapshot_ts"]).dt.total_seconds() / 3600
    sr = ev.set_index("event_id")
    won = pd.Series(np.nan, index=early.index)
    m = early["sack_row"] >= 0
    if m.any():
        wid = sack.loc[early.loc[m, "sack_row"].to_numpy(), "winner_id"].astype(str).to_numpy()
        won[m] = (early.loc[m, "id_home"].astype(str).to_numpy() == wid).astype(float)
    early["home_won"] = won
    return early


def report(e: pd.DataFrame) -> str:
    e = e.copy()
    e["d_dk"], e["d_pin"] = e["dk_close"] - e["dk"], e["pin_close"] - e["pin"]
    e["bucket"] = pd.cut(e["hours"], BUCKETS_H, right=False)
    lines = ["# DraftKings and Pinnacle: drift from earlier snapshots to the close", "",
             "Generated by `python -m upsets.dk_close`. Close = each match's last snapshot at least 5 min "
             "before its listed start with both books quoted (job C pulled these, 10-min cells). Every "
             "earlier snapshot with both books is compared with it. |Δp| = absolute change in the book's "
             "fair chance (proportional de-vig) of the home player, in percentage points. Aggregates only.", "",
             f"Matches with a close and at least one earlier snapshot: {e['event_id'].nunique():,}; "
             f"(match, earlier snapshot) pairs: {len(e):,}.", "",
             "| Hours before start | Pairs | DK median abs Δp | DK p90 | Pinnacle median abs Δp | Pinnacle p90 | "
             "Share moving > 5 pts (DK / Pin) | Corr(DK move, Pin move) |",
             "|---|---|---|---|---|---|---|---|"]
    for b, g in e.groupby("bucket", observed=True):
        corr = g["d_dk"].corr(g["d_pin"]) if len(g) > 2 else np.nan
        lines.append(
            f"| {b.left:g}–{b.right:g} h | {len(g):,} | {100 * g['d_dk'].abs().median():.1f} | "
            f"{100 * g['d_dk'].abs().quantile(0.9):.1f} | {100 * g['d_pin'].abs().median():.1f} | "
            f"{100 * g['d_pin'].abs().quantile(0.9):.1f} | {(g['d_dk'].abs() > 0.05).mean():.1%} / "
            f"{(g['d_pin'].abs() > 0.05).mean():.1%} | {corr:.2f} |")
    # does the close know more? log loss of early vs close on matches with a Sackmann result
    r = e.dropna(subset=["home_won"])
    if len(r):
        def ll(p):
            p = np.clip(p, 1e-6, 1 - 1e-6)
            return float(-np.mean(r["home_won"] * np.log(p) + (1 - r["home_won"]) * np.log(1 - p)))
        lines += ["", f"Accuracy on {r['event_id'].nunique():,} Sackmann-resolved matches ({len(r):,} pairs), "
                  "log loss of the home player's fair chance (lower is better):", "",
                  "| Book | Earlier snapshot | Close |", "|---|---|---|",
                  f"| DraftKings | {ll(r['dk']):.4f} | {ll(r['dk_close']):.4f} |",
                  f"| Pinnacle | {ll(r['pin']):.4f} | {ll(r['pin_close']):.4f} |",
                  "", "Mean move toward the eventual winner (pts; > 0 = the close leaned more to the winner): "
                  f"DK {100 * np.mean(np.where(r['home_won'] == 1, r['d_dk'], -r['d_dk'])):+.2f}, "
                  f"Pinnacle {100 * np.mean(np.where(r['home_won'] == 1, r['d_pin'], -r['d_pin'])):+.2f}."]
    return "\n".join(lines) + "\n"


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--sackmann", type=Path, default=Path("/home/user/phat-d0/tennis-sackmann-archive"))
    ap.add_argument("--cache", type=Path, default=dh.CACHE)
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args(argv)
    sack = sackmann.load(a.sackmann, start=2019)
    hs = {**dh.HIST_START, "other": pd.Timestamp("2024-01-01")}
    t = dh.tournaments(sack, dh._keys(), hist_start=hs, project_until=pd.Timestamp("2026-10-25"))
    j, snaps = dh.close_inputs(t, sack, root=a.cache)
    text = report(pairs(j, t, snaps, sack))
    print(text)
    if a.out:
        a.out.write_text(text)


if __name__ == "__main__":
    main()
